async function main() {
  console.log('Seeding writing questions...')

  for (const q of questions) {
    await prisma.writingQuestion.upsert({
      where: { source_id: q.id },
      update: {},
      create: {
        source_id: q.id,
        book_number: q.book,
        test_number: q.test,
        task_type: q.task === 'task1' ? 'task1' : 'task2',
        chart_type: q.chart_type,
        question_text: q.question,
        source: 'cambridge',
        difficulty: 'medium',
      }
    })
  }

  console.log(`Seeded ${questions.length} questions`)
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect())
